"""
Application audit history service — Slice 12.

Provides append-only persistence and retrieval of ApplicationEvent records.

Public interface:
  HistoryService.append_event(event)                         → None
  HistoryService.list_events_for_application(application_id) → list[ApplicationEvent]

Factory helpers (pure constructors, no I/O):
  make_application_created_event(application_id, initial_status, job_id, candidate_id)
  make_status_updated_event(application_id, old_status, new_status)
  make_notes_updated_event(application_id, old_notes, new_notes)

Design:
  - Events are stored in the "application_events" collection, keyed by event_id.
  - Each event_id is unique (generated by generate_id()), so saving by key is
    effectively append-only even though the underlying Repository supports overwrite.
  - list_events_for_application filters by application_id and returns events sorted
    oldest-first (ascending created_at), reconstructed via ApplicationEventAdapter.
  - No event is ever mutated after being written. The schema models are frozen=True.

This module contains no Streamlit code and no LLM calls.
"""
from __future__ import annotations

import logging

from app.schemas.application import ApplicationStatus
from app.schemas.application_event import (
    ApplicationCreatedEvent,
    ApplicationCreatedPayload,
    ApplicationEvent,
    ApplicationEventAdapter,
    NotesUpdatedEvent,
    NotesUpdatedPayload,
    StatusUpdatedEvent,
    StatusUpdatedPayload,
)
from app.storage.repository import Repository

logger = logging.getLogger(__name__)

_COLLECTION = "application_events"


# ---------------------------------------------------------------------------
# Service
# ---------------------------------------------------------------------------

class HistoryService:
    """Append-only audit trail for application lifecycle events."""

    def __init__(self, repo: Repository) -> None:
        self._repo = repo

    def append_event(self, event: ApplicationEvent) -> None:
        """Persist an event to the repository.

        The event is keyed by its event_id, which is unique per event.
        Calling this method twice with the same event object is idempotent
        (same key → same data), but callers should not rely on this.
        """
        self._repo.save(
            _COLLECTION,
            event.event_id,
            event.model_dump(mode="json"),
        )
        logger.debug(
            "Appended %s event '%s' for application '%s'",
            event.event_type.value,
            event.event_id,
            event.application_id,
        )

    def list_events_for_application(
        self,
        application_id: str,
    ) -> list[ApplicationEvent]:
        """Return all events for the given application, sorted oldest-first.

        Events from other applications are excluded. The result list is sorted
        by created_at ascending so callers see the full lifecycle in order.
        """
        all_raw = self._repo.load_all(_COLLECTION)
        events: list[ApplicationEvent] = []
        for raw in all_raw:
            if raw.get("application_id") != application_id:
                continue
            try:
                events.append(ApplicationEventAdapter.validate_python(raw))
            except Exception:
                logger.warning(
                    "Skipping malformed event record for application '%s': %r",
                    application_id,
                    raw,
                )
        return sorted(events, key=lambda e: e.created_at)


# ---------------------------------------------------------------------------
# Factory helpers — pure constructors, no I/O
# ---------------------------------------------------------------------------

def make_application_created_event(
    application_id: str,
    initial_status: ApplicationStatus,
    job_id: str,
    candidate_id: str,
) -> ApplicationCreatedEvent:
    """Build an ApplicationCreatedEvent with the given fields.

    Generates a unique event_id and sets created_at to the current UTC time
    via the model defaults. No I/O performed.
    """
    return ApplicationCreatedEvent(
        application_id=application_id,
        payload=ApplicationCreatedPayload(
            initial_status=initial_status,
            job_id=job_id,
            candidate_id=candidate_id,
        ),
    )


def make_status_updated_event(
    application_id: str,
    old_status: ApplicationStatus,
    new_status: ApplicationStatus,
) -> StatusUpdatedEvent:
    """Build a StatusUpdatedEvent recording a status transition.

    Generates a unique event_id and sets created_at to the current UTC time
    via the model defaults. No I/O performed.
    """
    return StatusUpdatedEvent(
        application_id=application_id,
        payload=StatusUpdatedPayload(
            old_status=old_status,
            new_status=new_status,
        ),
    )


def make_notes_updated_event(
    application_id: str,
    old_notes: str,
    new_notes: str,
) -> NotesUpdatedEvent:
    """Build a NotesUpdatedEvent recording a notes change.

    Generates a unique event_id and sets created_at to the current UTC time
    via the model defaults. No I/O performed.
    """
    return NotesUpdatedEvent(
        application_id=application_id,
        payload=NotesUpdatedPayload(
            old_notes=old_notes,
            new_notes=new_notes,
        ),
    )
